# The server's copy of what's solid (js/solids-data.js), measured from the game itself.
# Boots the game once per config (device class x season: each draws a little differently), measures the
# baked colliders there (js/solids-export.js), and keeps only what is solid in EVERY config, cell by cell,
# so the server never blocks a spot any player can see as open.
#   python3 tools/ci/solids-export.py http://127.0.0.1:8090 --write      regenerate js/solids-data.js
#   python3 tools/ci/solids-export.py http://127.0.0.1:8090 --check      CI: fail if js/solids-data.js is stale
import asyncio, base64, hashlib, json, os, re, shutil, sys
from playwright.async_api import async_playwright
BASE = sys.argv[1].rstrip('/')
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'js', 'solids-data.js')
OUT_V = os.path.join(ROOT, 'js', 'solids-v.js')  # just the version, for the client to tell the server which shapes it collides with
CONFIGS = [c for c in os.environ.get('SOLIDS_CONFIGS', 'pc:summer,phone:winter,tablet:autumn,pc:spring').split(',') if c]
ARGS = ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist']
Q = '/index.html?game=1&mode=walk&hour=15.5&weather=clear&season={season}&debug&noadapt&fastdt&noresume&nothrottle&unlock=all&mpserver=http://127.0.0.1:1&device={device}'
MEASURE = """(async()=>{const w=__garden.worlds.current;const g=w.debug.game;
  const fr=(n)=>new Promise(r=>{let k=0;const f=()=>{if(++k>=n)r();else requestAnimationFrame(f)};requestAnimationFrame(f)});
  const campsNow=()=>{let n=0;w.scene.traverse(o=>{if(/^camp-/.test(o.name))n++});return n};
  await fr(3); const p=g.player.position, sx=p.x, sz=p.z; g.player.teleport(-25,30,0);
  let camps=0;
  for(let i=0;i<60;i++){await fr(1);camps=campsNow();if(camps>0&&i>=2)break;}
  g.player.teleport(sx,sz,0); await fr(2);
  const m=await import('/js/solids-export.js'); const r=m.exportSolids(w); r.camps=camps; return r})()"""

def unpack(c):
    raw = base64.b64decode(c['bits']); n = c['nx'] * c['nz']
    return [(raw[i >> 3] >> (i & 7)) & 1 for i in range(n)]
def pack(bits):
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b: out[i >> 3] |= 1 << (i & 7)
    return base64.b64encode(bytes(out)).decode()
def cellset(grids):
    s = set()
    for c in grids:
        cs, ox, oz = c['cs'], round(c['x0'] / c['cs']), round(c['z0'] / c['cs'])
        for k, b in enumerate(unpack(c)):
            if b: s.add((ox + k % c['nx'], oz + k // c['nx']))
    return s
def keep(grids, allowed):
    out = []
    for c in grids:
        cs, ox, oz = c['cs'], round(c['x0'] / c['cs']), round(c['z0'] / c['cs'])
        bits = [b and ((ox + k % c['nx'], oz + k // c['nx']) in allowed) and 1 or 0 for k, b in enumerate(unpack(c))]
        if any(bits): out.append({**c, 'bits': pack(bits)})
    return out
def merge(runs):
    garden_sets = [cellset(r['garden']) for r in runs]
    both = set.intersection(*garden_sets)
    garden = keep(runs[0]['garden'], both)
    # the lowest top any config has for a name (a lower top only blocks less)
    tops = {}
    for r in runs:
        for c in r['garden']: tops[c['name']] = min(tops.get(c['name'], 1e9), c['top'])
    for c in garden: c['top'] = tops[c['name']]
    prefabs, odd = {}, []
    for k in runs[0]['prefabs']:
        if not all(k in r['prefabs'] for r in runs): odd.append(k); continue
        sets = [cellset(r['prefabs'][k]) for r in runs]
        prefabs[k] = keep(runs[0]['prefabs'][k], set.intersection(*sets))
    fixtures = {}
    for k, b in runs[0]['fixtures'].items():
        same = all(r['fixtures'].get(k) == b for r in runs)
        if same: fixtures[k] = b
        else: odd.append('fixture:' + k)
    gate = runs[0]['gate'] if all(r['gate'] == runs[0]['gate'] for r in runs) else None
    data = {'garden': garden, 'prefabs': prefabs, 'gate': gate, 'fixtures': fixtures}
    data['v'] = hashlib.sha1(json.dumps(data, sort_keys=True).encode()).hexdigest()[:12]
    data['configs'] = CONFIGS
    return data, odd
def render(data):
    return ('// GENERATED by tools/ci/solids-export.py --write from the game\'s own baked meshes. Do not edit.\n'
            '// What is solid in every device class and season (cell by cell), for the server (server/src/solids.js),\n'
            '// the spawn rules (server/src/garden.js) and the animals. CI (--check) fails when it no longer matches the game.\n'
            'export const SOLIDS = ' + json.dumps(data, separators=(',', ':'), sort_keys=True) + ';\n')

def render_v(data):
    return "// GENERATED by tools/ci/solids-export.py: the version of js/solids-data.js this build collides with.\nexport const SOLIDS_V = '" + data['v'] + "';\n"

async def main():
    runs = []
    async with async_playwright() as p:
        exe = shutil.which('google-chrome')
        b = await p.chromium.launch(headless=True, args=ARGS, **({'executable_path': exe} if exe else {}))
        for cfg in CONFIGS:
            device, season = cfg.split(':')
            ctx = await b.new_context(viewport={'width': 480, 'height': 270}); pg = await ctx.new_page()
            await pg.goto(BASE + Q.format(device=device, season=season), wait_until='commit', timeout=600000)
            await pg.wait_for_function("document.getElementById('veil').classList.contains('gone') && window.__garden && window.__garden.game", timeout=600000)
            r = await pg.evaluate(MEASURE)
            print(f"{cfg}: {len(r['garden'])} garden grids, {len(r['prefabs'])} camp prefabs (camps drawn: {r['camps']}), {len(r['fixtures'])} fixtures, mismatch {r['mismatch']}", flush=True)
            if r['mismatch']: print('FAIL camp props of one kind bake differently:', r['mismatch']); sys.exit(1)
            runs.append(r); await ctx.close()
        await b.close()
    data, odd = merge(runs)
    if odd: print('note: not the same in every config (left to the client):', odd)
    text = render(data)
    if '--write' in sys.argv:
        open(OUT, 'w').write(text); open(OUT_V, 'w').write(render_v(data))
        print(f'wrote {OUT} ({len(text)//1024} KB, v {data["v"]})')
    if '--check' in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        m = re.search(r'"v":"([0-9a-f]+)"', old)
        oldv = open(OUT_V).read() if os.path.exists(OUT_V) else ''
        if old.strip() != text.strip() or oldv.strip() != render_v(data).strip():
            print(f'FAIL js/solids-data.js is stale (committed v {m.group(1) if m else "?"}, game now v {data["v"]}): run tools/ci/solids-export.py --write'); sys.exit(1)
        print('ok   js/solids-data.js matches the game (v ' + data['v'] + ')')
asyncio.run(main())
